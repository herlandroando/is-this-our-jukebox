import { Glob } from "bun";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DIST = join(ROOT, "frontend", "dist");
const OUT = join(ROOT, "backend", "src", "embedded.ts");
const OUT_DIR = dirname(OUT);

const toImportName = (webPath: string): string =>
  "_a_" + webPath.replace(/[^A-Za-z0-9]+/g, "_").replace(/^_+|_+$/g, "") || "_a_root";

const MIME: Record<string, string> = {
  ".html": "text/html; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".js": "application/javascript; charset=utf-8",
  ".mjs": "application/javascript; charset=utf-8",
  ".json": "application/json; charset=utf-8",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".gif": "image/gif",
  ".webp": "image/webp",
  ".ico": "image/x-icon",
  ".txt": "text/plain; charset=utf-8",
  ".woff": "font/woff",
  ".woff2": "font/woff2",
  ".map": "application/json; charset=utf-8",
};

const sniff = (p: string): string => {
  if (p === "/" || p.endsWith("/index.html")) return MIME[".html"]!;
  const idx = p.lastIndexOf(".");
  if (idx < 0) return "application/octet-stream";
  return MIME[p.slice(idx).toLowerCase()] ?? "application/octet-stream";
};

const webPathOf = (rel: string): string => {
  const parts = rel.split(sep).join("/");
  if (parts === "index.html") return "/";
  if (parts.endsWith("/index.html")) return "/" + parts.slice(0, -"index.html".length);
  return "/" + parts;
};

async function listFiles(dir: string): Promise<string[]> {
  try {
    const out: string[] = [];
    const glob = new Glob("**/*");
    for await (const m of glob.scan({ cwd: dir, onlyFiles: true, followSymlinks: false })) {
      out.push(m.split("/").join(sep));
    }
    return out;
  } catch {
    return [];
  }
}

async function main() {
  const files = await listFiles(DIST);
  files.sort();
  if (files.length === 0) {
    console.warn(`[manifest] no files under ${DIST} — frontend build may not have run yet`);
  }

  const seen = new Set<string>();
  const imports: string[] = [];
  const entries: string[] = [];

  for (const rel of files) {
    const abs = join(DIST, rel);
    const webPath = webPathOf(rel);
    let importSpec = relative(OUT_DIR, abs).split(sep).join("/");
    if (!importSpec.startsWith(".")) {
      importSpec = "./" + importSpec;
    }
    const name = toImportName(webPath);
    if (seen.has(name)) throw new Error(`name collision: ${name} for ${webPath}`);
    seen.add(name);

    imports.push(
      `import ${name} from ${JSON.stringify(importSpec)} with { type: "file" };`,
    );
    entries.push(
      `  { webPath: ${JSON.stringify(webPath)}, contentType: ${JSON.stringify(sniff(webPath))}, path: ${name} },`,
    );
  }

  const lines: string[] = [];
  lines.push("// AUTO-GENERATED by scripts/build-manifest.ts — do not edit by hand.");
  lines.push("// Re-run `bun run build` to refresh embedded asset list.");
  lines.push("");
  if (imports.length === 0) {
    lines.push("// (no embedded assets — frontend/dist is empty)");
  } else {
    lines.push(...imports);
  }
  lines.push("");
  lines.push("export interface EmbeddedAssetMeta {");
  lines.push("  webPath: string;");
  lines.push("  contentType: string;");
  lines.push("  path: unknown;");
  lines.push("}");
  lines.push("");
  lines.push("export const EMBEDDED_ASSETS: EmbeddedAssetMeta[] = [");
  if (entries.length === 0) lines.push("  // empty");
  else lines.push(...entries);
  lines.push("];");
  lines.push("");

  await mkdir(OUT_DIR, { recursive: true });
  await writeFile(OUT, lines.join("\n"), "utf8");

  console.log(`[manifest] wrote ${entries.length} embedded assets -> ${relative(ROOT, OUT)}`);
  for (const rel of files) console.log(`  ${webPathOf(rel)}`);
}

await main();
